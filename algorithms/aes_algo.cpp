static const uint8_t RCON[11] = {
    0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

// GF(2^8) multiply by 2
static inline uint8_t xtime(uint8_t x) {
    return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0x00));
}

// GF(2^8) multiply
static inline uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        bool hi = (a & 0x80) != 0;
        a <<= 1;
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

// ---------------------------------------------------------------------------
// Key schedule: produces 11 round keys (each 16 bytes) = 176 bytes total
// ---------------------------------------------------------------------------
static void aes128_key_expand(const uint8_t key[16], uint8_t rk[176]) {
    memcpy(rk, key, 16);
    for (int i = 1; i <= 10; i++) {
        uint8_t* prev = rk + (i-1)*16;
        uint8_t* cur  = rk + i*16;

        // w[i*4+0] = w[(i-1)*4+0] XOR SubWord(RotWord(w[(i-1)*4+3])) XOR RCON[i]
        uint8_t t[4] = { prev[13], prev[14], prev[15], prev[12] };
        t[0] = SBOX[t[0]] ^ RCON[i];
        t[1] = SBOX[t[1]];
        t[2] = SBOX[t[2]];
        t[3] = SBOX[t[3]];

        cur[0]  = prev[0]  ^ t[0];
        cur[1]  = prev[1]  ^ t[1];
        cur[2]  = prev[2]  ^ t[2];
        cur[3]  = prev[3]  ^ t[3];
        cur[4]  = prev[4]  ^ cur[0];
        cur[5]  = prev[5]  ^ cur[1];
        cur[6]  = prev[6]  ^ cur[2];
        cur[7]  = prev[7]  ^ cur[3];
        cur[8]  = prev[8]  ^ cur[4];
        cur[9]  = prev[9]  ^ cur[5];
        cur[10] = prev[10] ^ cur[6];
        cur[11] = prev[11] ^ cur[7];
        cur[12] = prev[12] ^ cur[8];
        cur[13] = prev[13] ^ cur[9];
        cur[14] = prev[14] ^ cur[10];
        cur[15] = prev[15] ^ cur[11];
    }
}

// ---------------------------------------------------------------------------
// AES block operations (state is 4x4 column-major, i.e., state[col][row])
// ---------------------------------------------------------------------------
static void add_round_key(uint8_t state[4][4], const uint8_t* rk) {
    for (int c = 0; c < 4; c++)
        for (int r = 0; r < 4; r++)
            state[c][r] ^= rk[c*4 + r];
}

static void sub_bytes(uint8_t state[4][4]) {
    for (int c = 0; c < 4; c++)
        for (int r = 0; r < 4; r++)
            state[c][r] = SBOX[state[c][r]];
}

static void shift_rows(uint8_t state[4][4]) {
    // Row 1: shift left 1
    uint8_t t = state[0][1];
    state[0][1] = state[1][1]; state[1][1] = state[2][1];
    state[2][1] = state[3][1]; state[3][1] = t;
    // Row 2: shift left 2
    uint8_t t0 = state[0][2], t1 = state[1][2];
    state[0][2] = state[2][2]; state[1][2] = state[3][2];
    state[2][2] = t0;          state[3][2] = t1;
    // Row 3: shift left 3 (= right 1)
    t = state[3][3];
    state[3][3] = state[2][3]; state[2][3] = state[1][3];
    state[1][3] = state[0][3]; state[0][3] = t;
}

static void mix_columns(uint8_t state[4][4]) {
    for (int c = 0; c < 4; c++) {
        uint8_t s0 = state[c][0], s1 = state[c][1],
                s2 = state[c][2], s3 = state[c][3];
        state[c][0] = gmul(0x02,s0)^gmul(0x03,s1)^s2^s3;
        state[c][1] = s0^gmul(0x02,s1)^gmul(0x03,s2)^s3;
        state[c][2] = s0^s1^gmul(0x02,s2)^gmul(0x03,s3);
        state[c][3] = gmul(0x03,s0)^s1^s2^gmul(0x02,s3);
    }
}

// ---------------------------------------------------------------------------
// Single block encrypt (16 bytes in, 16 bytes out)
// ---------------------------------------------------------------------------
static void aes128_encrypt_block(const uint8_t in[16], uint8_t out[16], const uint8_t rk[176]) {
    // Load state (column-major)
    uint8_t state[4][4];
    for (int c = 0; c < 4; c++)
        for (int r = 0; r < 4; r++)
            state[c][r] = in[c*4 + r];

    add_round_key(state, rk);

    for (int round = 1; round <= 9; round++) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, rk + round*16);
    }
    // Final round (no MixColumns)
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, rk + 10*16);

    for (int c = 0; c < 4; c++)
        for (int r = 0; r < 4; r++)
            out[c*4 + r] = state[c][r];
}

// ---------------------------------------------------------------------------
// Key derivation: XOR-fold into 16 bytes.
// Not a standard KDF (no HKDF/PBKDF2) — intentional simplification for
// research comparison. Sufficient for comparing keystream diversity, not
// for production key management.
// ---------------------------------------------------------------------------
static void derive_aes_key(const std::vector<uint8_t>& key, uint8_t aes_key[16]) {
    memset(aes_key, 0, 16);
    for (size_t i = 0; i < key.size(); i++) {
        aes_key[i % 16] ^= key[i];
    }
}

