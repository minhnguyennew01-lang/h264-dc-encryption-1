// Generate 32-byte AES-CTR keystream with counter 0 and 1.
// Counter is fixed (no nalu_index) — demonstrates keystream-reuse weakness vs. hybrid.
static void aes_ctr_keystream(const uint8_t aes_key[16], uint8_t ks[32]) {
    uint8_t rk[176];
    aes128_key_expand(aes_key, rk);
    uint8_t ctr[16] = {};           // counter 0
    aes128_encrypt_block(ctr, ks, rk);
    ctr[15] = 1;                    // counter 1
    aes128_encrypt_block(ctr, ks + 16, rk);
}

std::vector<uint8_t> AESAlgo::encrypt(
    const std::vector<uint8_t>& dc_data,
    const std::vector<uint8_t>& key,
    int /*nalu_index*/)
{
    if (dc_data.size() < 25)
        throw std::runtime_error("AESAlgo::encrypt: dc_data too short ("
            + std::to_string(dc_data.size()) + " < 25)");
    uint8_t aes_key[16];
    derive_aes_key(key, aes_key);
    uint8_t ks[32];
    aes_ctr_keystream(aes_key, ks);

    std::vector<uint8_t> out(25);
    for (int i = 0; i < 25; i++)
        out[i] = dc_data[i] ^ ks[i];
    return out;
}

std::vector<uint8_t> AESAlgo::decrypt(
    const std::vector<uint8_t>& encrypted_data,
    const std::vector<uint8_t>& key,
    int /*nalu_index*/)
{
    if (encrypted_data.size() < 25)
        throw std::runtime_error("AESAlgo::decrypt: encrypted_data too short ("
            + std::to_string(encrypted_data.size()) + " < 25)");
    // XOR is its own inverse — same keystream as encrypt
    uint8_t aes_key[16];
    derive_aes_key(key, aes_key);
    uint8_t ks[32];
    aes_ctr_keystream(aes_key, ks);

    std::vector<uint8_t> out(25);
    for (int i = 0; i < 25; i++)
        out[i] = encrypted_data[i] ^ ks[i];
    return out;
}

// ---------------------------------------------------------------------------
// NIST FIPS-197 Appendix B test vector
// Key:   2b 7e 15 16 28 ae d2 a6 ab f7 15 88 09 cf 4f 3c
// Input: 32 43 f6 a8 88 5a 30 8d 31 31 98 a2 e0 37 07 34
// Expected output: 39 25 84 1d 02 dc 09 fb dc 11 85 97 19 6a 0b 32
// ---------------------------------------------------------------------------
bool AESAlgo::self_test() {
    static const uint8_t key[16] = {
        0x2b,0x7e,0x15,0x16, 0x28,0xae,0xd2,0xa6,
        0xab,0xf7,0x15,0x88, 0x09,0xcf,0x4f,0x3c
    };
    static const uint8_t plain[16] = {
        0x32,0x43,0xf6,0xa8, 0x88,0x5a,0x30,0x8d,
        0x31,0x31,0x98,0xa2, 0xe0,0x37,0x07,0x34
    };
    static const uint8_t expected[16] = {
        0x39,0x25,0x84,0x1d, 0x02,0xdc,0x09,0xfb,
        0xdc,0x11,0x85,0x97, 0x19,0x6a,0x0b,0x32
    };
    uint8_t rk[176];
    aes128_key_expand(key, rk);
    uint8_t out[16];
    aes128_encrypt_block(plain, out, rk);
    return memcmp(out, expected, 16) == 0;
}
